"""Generate the shared Luau catalog and a private, offline-only Ember UI file."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EMBER_SHA256 = "c6ec2ad2ad732a2ed704d044fd068b685d7e6c2613f60a07c39316666576390a"
MODULES = {
    "Catalog": "src/ui/Catalog.luau",
    "Settings": "src/storage/Settings.luau",
    "EmberAdapter": "src/ui/EmberAdapter.luau",
    "App": "src/App.luau",
}


def lua(value):
    if isinstance(value, dict):
        return "{" + ",".join(f"[{lua(k)}]={lua(v)}" for k, v in value.items()) + "}"
    if isinstance(value, list):
        return "{" + ",".join(map(lua, value)) + "}"
    if isinstance(value, str):
        # JSON strings are valid here: the catalog contains no control chars.
        assert not any(ord(char) < 32 for char in value)
        return json.dumps(value, ensure_ascii=False)
    if value is True:
        return "true"
    if value is False:
        return "false"
    if value is None:
        return "nil"
    return str(value)


def catalog_source():
    catalog = json.loads((ROOT / "preview/catalog.json").read_text(encoding="utf-8"))
    # One record per line makes generated diffs and source mapping readable.
    lines = ["-- Generated by tools/build_ui_prototype.py; edit preview/catalog.json.", "return {"]
    for key in ("version", "evidenceBuild"):
        lines.append(f"    {key} = {lua(catalog[key])},")
    for key in ("pages", "features"):
        lines.append(f"    {key} = {{")
        lines.extend("        " + lua(record) + "," for record in catalog[key])
        lines.append("    },")
    return "\n".join(lines + ["}", ""])


def prototype_source(ember):
    if hashlib.sha256(ember).hexdigest() != EMBER_SHA256:
        raise ValueError("Ember fingerprint differs from reviewed bytes; review before building")
    chunks = ["-- Idle Mafia Ember inert UI 0.1: no gameplay transport or account I/O.",
              "local modules = {}", "local Ember = (function()\n" + ember.decode("utf-8") + "\nend)()"]
    for name, relative in MODULES.items():
        source = (ROOT / relative).read_text(encoding="utf-8")
        chunks.append(f"modules.{name} = (function()\n{source}\nend)()")
    chunks.append("return modules.App.start({ Ember = Ember, Catalog = modules.Catalog, "
                  "Settings = modules.Settings, EmberAdapter = modules.EmberAdapter })")
    return "\n".join(chunks) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--ember", type=Path, help="Exact reviewed source; never downloaded or executed")
    args = parser.parse_args()
    expected = catalog_source()
    target = ROOT / MODULES["Catalog"]
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != expected:
            raise SystemExit("Generated Luau catalog is stale")
        print("Luau catalog matches JSON")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected, encoding="utf-8", newline="\n")
        print("Generated src/ui/Catalog.luau")
    if args.ember:
        output = ROOT / ".private/IdleMafia-Ember-UI-0.1.lua"
        source = prototype_source(args.ember.read_bytes())
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(source, encoding="utf-8", newline="\n")
        print(f"Built private inert UI: {output} ({len(source.encode('utf-8'))} bytes)")


if __name__ == "__main__":
    main()
